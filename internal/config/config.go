package config

import (
	"bufio"
	"errors"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Config contains the project metadata used to generate Android artifacts.
type Config struct {
	Name      string
	Package   string
	Version   string
	MinSDK    int
	TargetSDK int
	// BuildTools and NDK pin the Android toolchain versions the SDK installer
	// and the generated workflows use, so CI and a local install agree.
	BuildTools         string
	NDK                string
	Orientation        string
	Theme              string
	Source             string
	SourceDirs         []string
	GradleDependencies []string
	GoBuildTags        []string
	Obfuscate          bool

	// Keystore is the path, relative to the project root, of the keystore used
	// to sign release builds. Empty means releases are signed with the debug
	// key, which is installable but not publishable.
	Keystore string
	// KeystorePassword and KeyPassword may be supplied through the environment
	// (GO2APK_KEYSTORE_PASSWORD, GO2APK_KEY_PASSWORD) so they never need to be
	// committed.
	KeystorePassword string
	KeyAlias         string
	KeyPassword      string
}

// Signed reports whether a real release keystore has been configured.
func (c Config) Signed() bool {
	return c.Keystore != "" && c.KeyAlias != ""
}

// Default returns beginner-friendly Android application defaults.
func Default() Config {
	return Config{
		Name:        "My Go App",
		Package:     "com.example.goapp",
		Version:     "0.1.0",
		MinSDK:      23,
		TargetSDK:   36,
		BuildTools:  "36.0.0",
		NDK:         "27.2.12479018",
		Orientation: "unspecified",
		Theme:       "@style/AppTheme",
		Source:      ".",
		Obfuscate:   false,
	}
}

// Sources returns all Go source roots that should be parsed or watched.
func (c Config) Sources() []string {
	seen := make(map[string]bool)
	var out []string
	for _, src := range append([]string{c.Source}, c.SourceDirs...) {
		src = strings.TrimSpace(src)
		if src == "" || seen[src] {
			continue
		}
		seen[src] = true
		out = append(out, src)
	}
	return out
}

// Platform is the Android SDK platform package for the configured target SDK,
// for example "android-36".
func (c Config) Platform() string {
	return "android-" + strconv.Itoa(c.TargetSDK)
}

// Load reads go2apk.yaml values. It intentionally supports the simple
// key: value format generated by go2apk init so the CLI has no YAML runtime dependency.
func Load(path string) (Config, error) {
	cfg := Default()
	file, err := os.Open(path)
	if err != nil {
		return cfg, err
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	lineNo := 0
	for scanner.Scan() {
		lineNo++
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, ":")
		if !ok {
			return cfg, fmt.Errorf("%s:%d: invalid line %q; expected key: value", path, lineNo, line)
		}
		key = strings.TrimSpace(key)
		value = strings.Trim(strings.TrimSpace(value), "\"'")
		switch key {
		case "name":
			cfg.Name = value
		case "package":
			cfg.Package = value
		case "version":
			cfg.Version = value
		case "min_sdk":
			cfg.MinSDK, err = atoi(key, value)
		case "target_sdk":
			cfg.TargetSDK, err = atoi(key, value)
		case "build_tools":
			cfg.BuildTools = value
		case "ndk":
			cfg.NDK = value
		case "orientation":
			cfg.Orientation = value
		case "theme":
			cfg.Theme = value
		case "source":
			cfg.Source = value
		case "source_dirs":
			cfg.SourceDirs = splitCSV(value)
		case "gradle_dependencies", "android_dependencies":
			cfg.GradleDependencies = splitCSV(value)
		case "go_build_tags":
			cfg.GoBuildTags = splitCSV(value)
		case "obfuscate":
			cfg.Obfuscate, err = atob(key, value)
		case "keystore":
			cfg.Keystore = value
		case "keystore_password":
			cfg.KeystorePassword = value
		case "key_alias":
			cfg.KeyAlias = value
		case "key_password":
			cfg.KeyPassword = value
		default:
			return cfg, fmt.Errorf("%s:%d: unknown key %q", path, lineNo, key)
		}
		if err != nil {
			return cfg, fmt.Errorf("%s:%d: %w", path, lineNo, err)
		}
	}
	if err := scanner.Err(); err != nil {
		return cfg, err
	}
	return cfg, cfg.Validate()
}

// Validate checks that the configuration can produce a buildable Android
// project. Catching a bad package name or an impossible SDK range here is far
// cheaper than reading it out of a Gradle failure later.
func (c Config) Validate() error {
	if strings.TrimSpace(c.Name) == "" {
		return errors.New("name must not be empty")
	}
	if !javaPackageRE.MatchString(c.Package) {
		return fmt.Errorf("package %q is not a valid Android package name; expected lower-case dot-separated segments such as com.example.app", c.Package)
	}
	for _, segment := range strings.Split(c.Package, ".") {
		if javaReservedWords[segment] {
			return fmt.Errorf("package %q uses the Java reserved word %q in a segment", c.Package, segment)
		}
	}
	if strings.TrimSpace(c.Version) == "" {
		return errors.New("version must not be empty")
	}
	if c.MinSDK < minSupportedSDK {
		return fmt.Errorf("min_sdk %d is below the minimum supported value of %d", c.MinSDK, minSupportedSDK)
	}
	if c.TargetSDK < c.MinSDK {
		return fmt.Errorf("target_sdk %d must be greater than or equal to min_sdk %d", c.TargetSDK, c.MinSDK)
	}
	if strings.TrimSpace(c.BuildTools) == "" {
		return errors.New("build_tools must not be empty")
	}
	if strings.TrimSpace(c.NDK) == "" {
		return errors.New("ndk must not be empty")
	}
	if _, ok := orientations[c.Orientation]; !ok {
		return fmt.Errorf("orientation %q is not one of %s", c.Orientation, strings.Join(sortedOrientations(), ", "))
	}
	if strings.TrimSpace(c.Source) == "" {
		return errors.New("source must name the directory holding the app's Go code")
	}
	if c.Signed() {
		if c.KeyPassword == "" || c.KeystorePassword == "" {
			return errors.New("keystore and key passwords are required when a keystore is configured; " +
				"set them in go2apk.yaml or through GO2APK_KEYSTORE_PASSWORD / GO2APK_KEY_PASSWORD")
		}
	}
	return nil
}

// ResolveSecrets overlays credentials from the environment, which take
// precedence over anything written to go2apk.yaml.
func (c *Config) ResolveSecrets() {
	if v := os.Getenv("GO2APK_KEYSTORE_PASSWORD"); v != "" {
		c.KeystorePassword = v
	}
	if v := os.Getenv("GO2APK_KEY_PASSWORD"); v != "" {
		c.KeyPassword = v
	}
	if v := os.Getenv("GO2APK_KEY_ALIAS"); v != "" {
		c.KeyAlias = v
	}
	if v := os.Getenv("GO2APK_KEYSTORE"); v != "" {
		c.Keystore = v
	}
}

// minSupportedSDK is the oldest API level the Android Gradle Plugin the
// generated build.gradle pins will accept.
const minSupportedSDK = 21

var javaPackageRE = regexp.MustCompile(`^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$`)

var orientations = map[string]bool{
	"unspecified": true, "behind": true, "fullSensor": true, "fullUser": true,
	"landscape": true, "locked": true, "nosensor": true, "portrait": true,
	"reverseLandscape": true, "reversePortrait": true, "sensor": true,
	"sensorLandscape": true, "sensorPortrait": true, "user": true,
	"userLandscape": true, "userPortrait": true,
}

func sortedOrientations() []string {
	out := make([]string, 0, len(orientations))
	for name := range orientations {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

var javaReservedWords = map[string]bool{
	"abstract": true, "assert": true, "boolean": true, "break": true, "byte": true,
	"case": true, "catch": true, "char": true, "class": true, "const": true,
	"continue": true, "default": true, "do": true, "double": true, "else": true,
	"enum": true, "extends": true, "final": true, "finally": true, "float": true,
	"for": true, "goto": true, "if": true, "implements": true, "import": true,
	"instanceof": true, "int": true, "interface": true, "long": true, "native": true,
	"new": true, "package": true, "private": true, "protected": true, "public": true,
	"return": true, "short": true, "static": true, "strictfp": true, "super": true,
	"switch": true, "synchronized": true, "this": true, "throw": true, "throws": true,
	"transient": true, "try": true, "void": true, "volatile": true, "while": true,
}

func splitCSV(value string) []string {
	if value == "" {
		return nil
	}
	parts := strings.Split(value, ",")
	out := make([]string, 0, len(parts))
	seen := make(map[string]bool)
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part == "" || seen[part] {
			continue
		}
		seen[part] = true
		out = append(out, part)
	}
	return out
}

func atoi(key, value string) (int, error) {
	n, err := strconv.Atoi(value)
	if err != nil {
		return 0, fmt.Errorf("invalid %s value %q: %w", key, value, err)
	}
	return n, nil
}

func atob(key, value string) (bool, error) {
	b, err := strconv.ParseBool(value)
	if err != nil {
		return false, fmt.Errorf("invalid %s value %q: %w", key, value, err)
	}
	return b, nil
}
